const assert = require('node:assert/strict');
const fs = require('node:fs');
const { bundle, launchBrowser } = require('./browser-helpers.cjs');
(async () => {
  const code = await bundle('src/inline-search-editor.ts', 'Inline');
  const syntax = await bundle('src/search-syntax.ts', 'Syntax');
  const browser = await launchBrowser();
  try {
    const page = await browser.newPage({viewport:{width:850,height:350}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.setContent(`<style>body{background:#222;color:white;font:13px Arial}.native-search-bar{display:flex;align-items:center;position:relative;width:100%;background:#333}input{flex:1}button{flex-shrink:0}</style><style>${fs.readFileSync('public/styles.css','utf8')}</style><div class="native-search-bar"><input name="filter" placeholder="Search"><button class="aegis-search-widget">Shield</button><button>Star</button><button>Clear</button></div><script>${code}\n${syntax}\nwindow.changes=[]; const input=document.querySelector('input'); input.__reactProps$test={onChange:e=>changes.push(e.target.value),onKeyDown:e=>{if(e.key==='Tab'){e.preventDefault();input.setSelectionRange(0,input.value.length);document.execCommand('insertText',false,'is:handcannon ');}}}; window.dispose=Inline.attachInlineSearchEditor(input, term => /^(aegis:|is:(solar|arc|handcannon)$|notes:)/.test(term));</script>`);
    const editor=page.locator('.aegis-inline-search'), input=page.locator('input');
    await editor.click();
    await page.keyboard.type('is:sol');
    assert.equal(await editor.locator('.aegis-search-token').count(),0,'Partial terms stay plain text');
    await page.keyboard.type('ar');
    assert.equal(await editor.locator('.aegis-search-token').count(),0,'A valid term stays plain while typing');
    await page.keyboard.press('Space');
    assert.equal(await editor.locator('.aegis-search-token').count(),1,'Space commits a valid term');
    assert.equal(await editor.locator('.aegis-search-token').getAttribute('contenteditable'),'false','Badges are immutable');
    await page.keyboard.press('Backspace');
    await page.keyboard.press('Backspace');
    assert.equal(await input.inputValue(),'','Backspace removes the whole badge');
    await page.keyboard.type('is:unknown ');
    assert.equal(await editor.locator('.aegis-search-token').count(),0,'Invalid filters never become badges');
    await page.keyboard.press('Control+a');await page.keyboard.press('Backspace');
    await page.keyboard.type('is:solar');await page.keyboard.press('Enter');
    assert.equal(await editor.locator('.aegis-search-token').count(),1,'Enter commits a valid term');
    await page.keyboard.press('Control+z');
    assert.equal(await input.inputValue(),'is:solar','Undo conversion preserves the complete draft');
    assert.equal(await editor.locator('.aegis-search-token').count(),0,'Undo conversion restores plain text');
    await page.keyboard.press('Control+Shift+z');
    assert.equal(await editor.locator('.aegis-search-token').count(),1,'Redo restores the immutable badge');
    await page.keyboard.type('aegis:');
    assert.equal(await input.inputValue(),'is:solar aegis:','Typing after a badge starts a separate draft');
    assert.equal(await editor.locator('.aegis-search-token').count(),1);
    // Remove only the separating space. It must not combine immutable text with the draft.
    await page.keyboard.press('Home');
    await page.keyboard.press('ArrowRight');
    await page.keyboard.press('Delete');
    assert.equal(await input.inputValue(),'is:solar aegis:','Deleting a separator cannot edit the badge');
    await page.keyboard.press('Control+a');await page.keyboard.press('Backspace');
    assert.equal(await input.evaluate(el=>getComputedStyle(el).position),'absolute','Native input is hidden without relying on DIM parent classes');
    await input.evaluate(el=>{el.className='native-invalid-query';});
    assert.equal(await input.evaluate(el=>getComputedStyle(el).position),'absolute','React className changes cannot reveal a duplicate native input');
    const query='(aegis:p:>=s OR aegis:p:>=a) AND is:solar ';
    await page.keyboard.type(query);
    assert.equal(await input.inputValue(),query,'Typing and spaces preserve full native query');
    await input.evaluate(el=>{el.__reactProps$test.onChange=e=>{changes.push(e.target.value);el.focus();};});
    await page.keyboard.type('x');
    assert.equal(await editor.evaluate(el=>document.activeElement===el),true,'DIM focus restoration stays in the visible editor');
    await page.keyboard.press('Backspace');
    assert.equal(await input.inputValue(),query);
    await input.evaluate(el=>{el.__reactProps$test.onChange=e=>changes.push(e.target.value);});
    assert.equal(await editor.locator('.aegis-search-token').count(),3);
    assert.equal(await editor.locator('.aegis-search-operator').count(),2);
    assert.equal(await editor.locator('.aegis-search-paren').count(),2);
    await editor.getByRole('button',{name:'Remove aegis:p:>=s',exact:true}).click();
    assert.equal(await input.inputValue(),'aegis:p:>=a is:solar','Remove cleans group and operators');
    await page.keyboard.press('Control+z');
    assert.equal(await input.inputValue(),query,'Undo removal');
    await page.keyboard.press('Control+Shift+z');
    assert.equal(await input.inputValue(),'aegis:p:>=a is:solar','Redo removal');
    await page.keyboard.press('Control+a');
    // Firefox creates its own DataTransfer for synthetic clipboard events.
    // Read and seed the event's store rather than assuming constructor identity.
    const copied=await editor.evaluate(el=>{const event=new ClipboardEvent('copy',{clipboardData:new DataTransfer(),bubbles:true,cancelable:true});el.dispatchEvent(event);return event.clipboardData.getData('text/plain')});
    assert.equal(copied,'aegis:p:>=a is:solar','Copy excludes remove glyphs');
    await editor.evaluate(el=>{const event=new ClipboardEvent('paste',{clipboardData:new DataTransfer(),bubbles:true,cancelable:true});event.clipboardData.setData('text/plain','notes:"two  spaces"\naegis:god');el.dispatchEvent(event);});
    assert.equal(await input.inputValue(),'notes:"two  spaces" aegis:god','Paste preserves quoted spacing');
    await page.keyboard.press('Backspace');
    assert.equal(await input.inputValue(),'notes:"two  spaces" aegis:go','Backspace edits text, not close button');
    await page.keyboard.press('Home');
    await page.keyboard.type('x');
    assert.equal(await input.inputValue(),'x notes:"two  spaces" aegis:go','Typing at beginning');
    assert.equal(await editor.locator('.aegis-search-term').first().textContent(),'x','A draft before a badge stays editable');
    await input.evaluate(el=>{el.value='is:arc AND aegis:god';});
    await page.waitForFunction(()=>document.querySelector('.aegis-inline-search').textContent.includes('is:arc'));
    assert.equal(await editor.locator('.aegis-search-token').count(),2,'External native changes reflected');
    await editor.focus();await page.keyboard.press('Tab');
    await page.waitForFunction(()=>document.querySelector('.aegis-inline-search').textContent.includes('is:handcannon'));
    assert.equal(await input.inputValue(),'is:handcannon ','Native Tab completion');
    // Composition can insert directly into the trailing caret node or split a
    // draft into several text nodes. Reconcile those native edits exactly once.
    await editor.evaluate(el=>{
      el.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));
      const tail=el.lastChild;tail.textContent='notes:日本';
      document.getSelection().setBaseAndExtent(tail,tail.textContent.length,tail,tail.textContent.length);
      el.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true,data:'日本'}));
    });
    assert.equal(await input.inputValue(),'is:handcannon notes:日本','Composition publishes native tail edits');
    await page.keyboard.type('語');
    assert.equal(await input.inputValue(),'is:handcannon notes:日本語','Typing resumes at the composed caret');
    assert.equal(await editor.textContent(),'is:handcannon× notes:日本語','Composition must not leave duplicate tail text');
    await editor.evaluate(el=>{
      el.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));
      const draft=el.querySelector('.aegis-search-term');
      draft.append(document.createTextNode('テスト'));
      const tail=draft.lastChild;
      document.getSelection().setBaseAndExtent(tail,tail.textContent.length,tail,tail.textContent.length);
      el.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true,data:'テスト'}));
    });
    assert.equal(await input.inputValue(),'is:handcannon notes:日本語テスト','Composition reads split draft nodes');
    assert.equal(await editor.textContent(),'is:handcannon× notes:日本語テスト','Native draft nodes are normalized without duplicate text');
    await page.keyboard.press('Space');
    assert.equal(await editor.locator('.aegis-search-token').count(),2,'Composed text converts only after commitment');
    const cases=[['a OR b AND c',0,'b c'],['a OR b AND c',5,'a or c'],['-(a OR b) c',2,'-(b) c'],['a a b',2,'a b'],['a',0,''],['a AND notes:"draft',0,' AND notes:"draft']];
    for(const [query,start,expected] of cases) assert.equal(await page.evaluate(([q,s])=>Syntax.removeSearchTerm(q,s),[query,start]),expected,query);
    const rich='(aegis:p:>=s OR aegis:p:>=a) AND notes:"two  spaces" -is:solar /* note */';
    assert.equal(await page.evaluate(q=>Syntax.tokenizeSearch(q).map(t=>t.text).join(''),rich),rich,'Tokenizer round trip');
    await input.evaluate((el,q)=>{el.value=q},rich);
    await page.waitForFunction(()=>document.querySelector('.aegis-inline-search').textContent.includes('note */'));
    await page.screenshot({path:'scratch/inline-search-editor.png'});
    await page.setViewportSize({width:360,height:350});
    const overlap=await page.evaluate(()=>{const e=document.querySelector('.aegis-inline-search').getBoundingClientRect(),s=document.querySelector('.aegis-search-widget').getBoundingClientRect();return e.right>s.left+1;});
    assert.equal(overlap,false,'Narrow viewport retains shield space');
    await editor.focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await editor.evaluate(el=>document.activeElement===el),false,'Shift+Tab leaves the field instead of completing a term');
    assert.equal(await input.inputValue(),rich);
    await editor.focus();
    await input.evaluate(el=>{window.testProps=el.__reactProps$test;delete el.__reactProps$test;});
    await page.waitForFunction(()=>!document.querySelector('.aegis-inline-search'));
    assert.equal(await input.inputValue(),rich,'Unsupported DIM hooks preserve the complete query');
    assert.equal(await input.getAttribute('data-aegis-native-search'),null,'Unsupported hooks restore DIM input visibility');
    assert.equal(await input.evaluate(el=>document.activeElement===el),true,'Fallback restores native input focus');
    await page.evaluate(()=>{dispose=Inline.attachInlineSearchEditor(document.querySelector('input'));});
    assert.equal(await editor.count(),0,'Unsupported inputs never acquire an unusable editor');
    await input.evaluate(el=>{el.__reactProps$test=window.testProps;el.value='is:arc';window.termReady=false;window.dispose=Inline.attachInlineSearchEditor(el,()=>window.termReady);});
    assert.equal(await editor.locator('.aegis-search-token').count(),0,'A committed term waits for native validation');
    await page.evaluate(()=>{window.termReady=true;});
    await page.waitForFunction(()=>document.querySelector('.aegis-search-token'));
    await page.evaluate(()=>{window.termReady=false;});
    await editor.focus();await page.keyboard.press('End');await page.keyboard.press('Space');
    assert.equal(await editor.locator('.aegis-search-token').getAttribute('contenteditable'),'false','Data refresh cannot turn accepted badges into editable text');
    await page.evaluate(()=>dispose());
    assert.equal(await editor.count(),0);assert.equal(await input.getAttribute('aria-hidden'),null);
    assert.deepEqual(errors,[]);
    console.log('PASS: inline typing, removal, Boolean cleanup, undo/redo, clipboard, autocomplete, external synchronization, responsive layout, and disposal');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
